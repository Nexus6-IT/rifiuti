/**
 * Colonne documentate delle tabelle WinWaste che entrano nello staging.
 *
 * Fonte: schema reale ricavato dai database modello dell'installer
 * (`docs/schema-db-winwaste.md` nel progetto WinWaste, catalogo `sys.columns`,
 * ordine di `column_id`). Il manifest dichiara le colonne effettivamente
 * estratte; il lettore le confronta con questo elenco e segnala le differenze
 * come avvisi (le versioni di WinWaste cambiano lo schema), mai come errori.
 *
 * Tutte le colonne viaggiano nello staging come stringhe o `null`: il tipo SQL
 * qui sotto e' solo documentazione (serve all'estrattore per scegliere il
 * CAST e a chi legge per capire il formato del testo).
 *
 * FILE GENERATO DAL CATALOGO: non riordinare le colonne a mano.
 */

export interface ColonnaDocumentata {
  readonly nome: string
  /** Tipo SQL Server nel database modello (documentazione). */
  readonly tipoSql: string
}

export interface TabellaDocumentata {
  /** Nome SQL Server esatto (puo' contenere spazi). */
  readonly nome: string
  /** File JSON Lines nella cartella dello staging. */
  readonly file: string
  /** Sezione della documentazione WinWaste da cui viene l'elenco. */
  readonly fonte: string
  readonly colonne: readonly ColonnaDocumentata[]
  /**
   * Database in cui sta la tabella: `PRINCIPALE` (`WW<ditta><anno>`, default) oppure
   * `MUD` (`ww<azienda>MU<aa>`, estratto a parte dal pezzo I11).
   */
  readonly database?: 'PRINCIPALE' | 'MUD'
  /**
   * Colonne del database che NON si estraggono (contenuti binari o testo di file gia' presenti
   * altrove): il catalogo non le elenca e la `SELECT` non le legge.
   */
  readonly escluse?: readonly string[]
}

